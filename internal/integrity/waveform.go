// The waveform half of the relocation story, and since backlog B652 its
// repair.
//
// `track_analysis.waveform_path` is absolute, exactly like
// `track_variants.sidecar_path`, and it has the same failure: copy the
// database to a host where `dataDir` sits elsewhere — or move the
// directory — and every row reads ENOENT while every curve sits,
// byte-identical, at its source-mirrored place under the CURRENT one.
//
// It is the WORSE half, and that is why it needed its own change rather
// than riding along with the variants one (#937 named it; #938 still
// tracks the schema-relative follow-up). A variant that reads missing
// gets regenerated by the auto-optimize sweeper, expensively but
// automatically. A waveform does not: the analysis skip gate keys on the
// SOURCE's mtime and size, both unchanged by a host move or a deleted
// curve, so the candidate walk never offers the track again. BEFORE
// adoption that left `/v1/waveform` answering 410 forever and `bridge
// doctor` prescribing a full re-decode to recover curves that were
// already on disk.
//
// LocateWaveform classifies, and DecideWaveform gives each of its
// verdicts what a lookup does about it (WaveformAction):
//
//   - present: the recorded path holds the curve; serve it.
//   - relocated: the recorded path is gone and the canonical one holds a
//     file of the recorded size; analysisStoreAdapter.LookupAnalysis adopts
//     it on the first lookup, serving from the canonical path and
//     rewriting the row, with no `indexed_at` bump, because a path
//     correction changes nothing a client can see (#954).
//   - missing: ENOENT at the recorded path and at the canonical one, the
//     only proof that a curve is gone. Its regeneration is asked for, and
//     the curve is rendered again at the canonical path, waveform only,
//     the row's other measurements kept (analyze.RunWaveformRepair).
//   - mismatched: the recorded path is gone and the canonical path holds a
//     file of another size, a partial copy. Regeneration may replace it,
//     written beside it and renamed over it, never deleted first.
//   - unknown: a stat failed otherwise (EACCES, EIO, a wedged mount), which
//     proves nothing: the row and whatever is on disk are left as they are.
//
// A regeneration is a decode, so it is guarded twice. Before the first,
// and then at most once per interval, the WHOLE catalog is judged, never
// the one row (JudgeWaveformCatalog, WaveformRegenGuard): a waveform
// directory that is missing, holds no curve (what a volume that is away
// looks like, and a directory emptied by hand, the last curve's deletion
// included; a curve is a regular file, never a link), cannot be read, or
// has lost more than WaveformRegenMaxMissingPercent of the catalog's
// curves while it still holds curves (massMissingRefusal, the variant
// reapers' relocation decision over the waveform family), regenerates
// nothing, one track at a time or otherwise, the tree looked at again for
// a curve just before a judgment admits; and `bridge doctor`'s
// waveform-regeneration line says why. And the job carries the identity of
// the waveform directory the judgment saw. A volume that goes before the
// decode is done gets nothing at all and no strike: the path is asked
// before the source is opened, and the directory is opened as the repair's
// root only after the decode, on that identity alone. One that goes after
// the root opened gets nothing at its path and no strike either: every
// directory, scratch, removal, rename and sync of the repair goes through
// the root (analyze.RunWaveformRepair), which keeps the directory it
// opened, and the path is compared with the root again before the rename
// and right before the commit, which is refused; what the root reached
// meanwhile (the curve's directories, at most the curve) is in the
// directory it opened, and nothing records it.
//
// Deliberately NOT a reaper. Nothing here deletes: LocateWaveform
// classifies, the adapter adopts, and a repair only ever renames a curve
// over the place it belongs. There is still no proactive waveform sweep:
// a curve heals when its track is next asked for (a /v1/waveform lookup,
// never /v1/spectrum's), and not before.

// WaveformSnapshot is the subset of a `track_analysis` row the
// relocation probe needs. The waveform twin of VariantSnapshot.
type WaveformSnapshot struct {
	// SourcePath is the library-relative path the row is keyed on, and
	// the input the canonical layout is derived from.
	SourcePath string
	// WaveformPath is the absolute path the row RECORDS.
	WaveformPath string
	// SizeBytes is the row's recorded sidecar size, compared against a
	// file found at the canonical location so a partial copy is never
	// adopted.
	SizeBytes int64
}

// CanonicalWaveformPath is where row's curve belongs under waveformDir
// — `analyze.AnalyzeSpec.SidecarPath()`, the one layout the analysis
// pool writes and `analyze --gc`'s known set already derives. Empty
// when the row carries no source identity or no directory is known, so
// a caller can range over rows and skip the empties.
//
// Derived from the owning package rather than re-spelled here, for the
// reason CanonicalSidecarPath delegates to transcode.VariantSidecarPath:
// two copies of a layout is two things that can drift, and the one that
// drifts is the one that decides whether a file is adopted or orphaned.
func CanonicalWaveformPath(waveformDir string, row WaveformSnapshot) string {
	if waveformDir == "" || row.SourcePath == "" {
		return ""
	}
	return analyze.AnalyzeSpec{OutputDir: waveformDir, SourceLibraryRel: row.SourcePath}.SidecarPath()
}

// LocateWaveform stats the recorded path and, on ENOENT, the canonical
// one. Pure classification — it writes nothing, so the caller acts on
// the verdict in its own way.
//
// It DELEGATES to locateRecordedFile rather than restating the ladder:
// this and LocateSidecar make the same decision about two different
// tables, and there is no reading on which they should answer
// differently. A second copy would be a second place to fix the day a
// verdict moves, and the copy that drifts is the one deciding whether a
// file is adopted or stranded. All this function owns is WHERE a
// waveform belongs; the classifier owns what the answer means.
func LocateWaveform(waveformDir string, row WaveformSnapshot) SidecarLocation {
	return locateRecordedFile(row.WaveformPath, CanonicalWaveformPath(waveformDir, row), row.SizeBytes)
}

// WaveformAction is what a lookup does about a row's curve, given the
// verdict LocateWaveform reached (DecideWaveform).
type WaveformAction uint8

const (
	// WaveformServe — SidecarPresent: the recorded path holds the curve.
	WaveformServe WaveformAction = iota
	// WaveformAdopt — SidecarRelocated: rewrite the row to the canonical
	// path, where a file of the recorded size is, and serve it from there.
	WaveformAdopt
	// WaveformRegenerate — SidecarMissing, ENOENT at the recorded path and
	// at the canonical one: the curve is gone, and may be rendered again
	// at the canonical path under the catalog's guard.
	WaveformRegenerate
	// WaveformReplace — SidecarMismatched: the recorded path is gone and
	// the canonical path holds a file of another size, a partial copy.
	// Rendered again under the same guard, the new curve is written beside
	// the copy and renamed over it, never by deleting it first.
	WaveformReplace
	// WaveformLeave — SidecarUnknown, a stat that failed otherwise than
	// ENOENT, or a missing curve with no canonical place to render one
	// (no waveform directory known): nothing proves the curve gone, or
	// nothing could take its place. The row and the disk are left as
	// they are.
	WaveformLeave
)

// String names the action for logs and test failures.
func (a WaveformAction) String() string {
	switch a {
	case WaveformServe:
		return "serve"
	case WaveformAdopt:
		return "adopt"
	case WaveformRegenerate:
		return "regenerate"
	case WaveformReplace:
		return "replace"
	case WaveformLeave:
		return "leave"
	}
	return "WaveformAction(?)"
}

// WaveformDecision is LocateWaveform's verdict on a row and the action it
// leads to.
type WaveformDecision struct {
	SidecarLocation
	Action WaveformAction
	// Target is where a curve rendered again goes, the row's canonical path
	// under the waveform directory: set for WaveformRegenerate and
	// WaveformReplace, empty otherwise. Not SidecarLocation.Canonical,
	// which is empty for a row whose recorded path already IS the canonical
	// one (the ordinary curve deleted where it was written).
	Target string
}

// Regenerates reports whether the action renders the curve again.
func (d WaveformDecision) Regenerates() bool {
	return d.Action == WaveformRegenerate || d.Action == WaveformReplace
}

// DecideWaveform is LocateWaveform with each verdict's action: the one
// place a verdict becomes adopt, regenerate, replace or leave, so the serve
// lookup, the catalog judgment and the doctor cannot read one verdict two
// ways.
func DecideWaveform(waveformDir string, row WaveformSnapshot) WaveformDecision {
	canonical := CanonicalWaveformPath(waveformDir, row)
	loc := locateRecordedFile(row.WaveformPath, canonical, row.SizeBytes)
	d := WaveformDecision{SidecarLocation: loc}
	switch loc.Verdict {
	case SidecarPresent:
		d.Action = WaveformServe
	case SidecarRelocated:
		d.Action = WaveformAdopt
	case SidecarMissing:
		d.Action = WaveformRegenerate
	case SidecarMismatched:
		d.Action = WaveformReplace
	default:
		d.Action = WaveformLeave
	}
	if d.Regenerates() {
		if canonical == "" {
			d.Action = WaveformLeave
		} else {
			d.Target = canonical
		}
	}
	return d
}

// ConsiderWaveformSidecar reports whether a basename is a waveform curve
// the analysis pool writes (analyze.WaveformExt): the recogniser of the
// waveform family (waveformSidecars), which the regeneration guard's probe
// walks the waveform directory with and `analyze --gc` weighs its files
// by, so a file one counts as a curve is a file the other reclaims. A
// curve's scratch (analyze.AnalysisTmpSuffix after the extension) is not a
// curve.
func ConsiderWaveformSidecar(name string) bool {
	return strings.HasSuffix(name, analyze.WaveformExt)
}
